#!/usr/bin/env python3
"""Focused tests for add_purpose_line.py.

This script writes a sentence into every reader-facing page that lacks one, so a
defect here is a defect repeated across the whole documentation tree. The tests
below pin the decisions that determine what gets written and, just as importantly,
what is deliberately left alone.
"""

from __future__ import annotations

from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).parent))

from add_purpose_line import (
    derive_purpose,
    has_purpose_line,
    insert_purpose,
    is_autogenerated,
    parse_frontmatter,
    unquote,
)


class DerivePurposeTests(unittest.TestCase):
    """The derived sentence must add no claim the page cannot support."""

    def test_verb_follows_doc_type(self) -> None:
        """Diátaxis type drives the opening verb, per the steering rule."""
        cases = {
            "tutorial": "shows how to",
            "how-to": "shows how to",
            "reference": "documents",
            "explanation": "explains",
        }
        for doc_type, verb in cases.items():
            with self.subTest(doc_type=doc_type):
                line = derive_purpose(
                    {
                        "audience": "operators",
                        "description": "Back up and restore cluster state",
                        "doc_type": doc_type,
                    }
                )
                self.assertIn(verb, line)
                self.assertTrue(line.startswith("**Purpose:** For operators,"))

    def test_unknown_doc_type_falls_back_to_documents(self) -> None:
        line = derive_purpose(
            {"audience": "operators", "description": "Some topic", "doc_type": "guide"}
        )
        self.assertIn("documents", line)

    def test_missing_audience_does_not_emit_an_empty_clause(self) -> None:
        line = derive_purpose({"description": "Some topic", "doc_type": "reference"})
        self.assertIn("For all readers,", line)
        self.assertNotIn("For ,", line)

    def test_missing_description_produces_a_generic_sentence(self) -> None:
        line = derive_purpose({"audience": "operators", "doc_type": "reference"})
        self.assertTrue(line.startswith("**Purpose:** For operators, documents"))
        self.assertNotIn("  ", line)

    def test_description_is_reused_verbatim_without_new_claims(self) -> None:
        """The sentence may restate the description but must not extend it."""
        description = "Configure OpenStack networking for a production cluster"
        line = derive_purpose(
            {"audience": "operators", "description": description, "doc_type": "how-to"}
        )
        self.assertIn("configure OpenStack networking for a production cluster", line)

    def test_trailing_period_is_not_doubled(self) -> None:
        line = derive_purpose(
            {"audience": "operators", "description": "Some topic.", "doc_type": "reference"}
        )
        self.assertTrue(line.endswith("."))
        self.assertNotIn("..", line)

    def test_stutter_is_removed_when_the_verb_restates_the_description(self) -> None:
        """"explains" + "Explains how X works" must not read "explains explains"."""
        line = derive_purpose(
            {
                "audience": "operators",
                "description": "Explains how the configuration lifecycle works",
                "doc_type": "explanation",
            }
        )
        self.assertEqual(
            line, "**Purpose:** For operators, explains how the configuration lifecycle works."
        )

    def test_proper_nouns_keep_their_capitalisation(self) -> None:
        line = derive_purpose(
            {"audience": "operators", "description": "Kubernetes upgrade paths", "doc_type": "reference"}
        )
        self.assertIn("Kubernetes upgrade paths", line)


class InsertionTests(unittest.TestCase):
    """Where the line lands, and what must never be overwritten."""

    def test_line_is_inserted_after_the_h1(self) -> None:
        text = "---\nid: x\n---\n# Manage secrets\n\nBody text.\n"
        result = insert_purpose(text, "**Purpose:** For operators, documents secrets.")
        lines = result.splitlines()
        self.assertEqual(lines[3], "# Manage secrets")
        self.assertEqual(lines[5], "**Purpose:** For operators, documents secrets.")

    def test_existing_purpose_line_is_never_replaced(self) -> None:
        """Hand-written wording must survive a re-run.

        Without this, a second sweep would overwrite curated sentences with
        machine-derived ones and the damage would be indistinguishable from
        intentional text in review.
        """
        original = (
            "---\nid: x\n---\n# Manage secrets\n\n"
            "**Purpose:** For operators, hand-written wording that must survive.\n\n"
            "Body text.\n"
        )
        result = insert_purpose(original, "**Purpose:** derived replacement.")
        self.assertIn("hand-written wording that must survive", result)
        self.assertNotIn("derived replacement", result)

    def test_page_without_a_heading_gets_a_synthesised_one(self) -> None:
        """Documented behaviour: a title is synthesised so the line has an anchor.

        Some legacy how-to pages omit the H1 entirely. Refusing to write would
        leave them permanently non-compliant, so the script creates the heading
        from the supplied title rather than skipping the page.
        """
        original = "---\nid: x\n---\nBody with no heading at all.\n"
        result = insert_purpose(original, "**Purpose:** For operators, documents x.", "Legacy page")
        self.assertIn("# Legacy page", result)
        self.assertIn("**Purpose:** For operators, documents x.", result)
        # The body must still follow the inserted block, not be dropped.
        self.assertIn("Body with no heading at all.", result)

    def test_frontmatter_is_untouched(self) -> None:
        original = "---\nid: x\ntitle: \"Keep me\"\n---\n# Title\n\nBody.\n"
        result = insert_purpose(original, "**Purpose:** For operators, documents x.")
        self.assertIn('title: "Keep me"', result)
        self.assertTrue(result.startswith("---\nid: x\n"))


class SkipDecisionTests(unittest.TestCase):
    """Generated and already-compliant pages must be left to their owners."""

    def test_cobra_generated_pages_are_skipped(self) -> None:
        """docs-gen owns these pages and emits the line itself.

        The current generator renders the heading as an H2 command path, the shape
        that made this guard inert once: an H1-only matcher matched nothing and the
        sweep reported "0 auto-generated pages skipped".
        """
        self.assertTrue(is_autogenerated("## opencenter cluster reconcile\n"))
        self.assertTrue(is_autogenerated("## opencenter\n"))
        self.assertTrue(is_autogenerated("# Opencenter_Cluster_Reconcile\n"))
        self.assertTrue(is_autogenerated("# opencenter cluster\n"))

    def test_curated_pages_are_not_skipped(self) -> None:
        self.assertFalse(is_autogenerated("# Manage secrets\n"))

    def test_purpose_detection_accepts_both_spellings(self) -> None:
        self.assertTrue(has_purpose_line("**Purpose:** For operators, documents x."))
        self.assertTrue(has_purpose_line("> **Purpose** For operators, documents x."))
        self.assertFalse(has_purpose_line("# Title\n\nNo purpose here.\n"))


class FrontmatterParsingTests(unittest.TestCase):
    def test_missing_frontmatter_returns_none(self) -> None:
        self.assertIsNone(parse_frontmatter("# Title\n\nBody.\n"))

    def test_values_are_unquoted(self) -> None:
        self.assertEqual(unquote('"platform engineers"'), "platform engineers")
        self.assertEqual(unquote("'operators'"), "operators")
        self.assertEqual(unquote("operators"), "operators")

    def test_colon_inside_a_value_survives_parsing(self) -> None:
        text = "---\nid: x\ndescription: \"Docs: exactly this\"\n---\n# T\n"
        parsed, _ = parse_frontmatter(text)
        self.assertEqual(unquote(parsed["description"]), "Docs: exactly this")


if __name__ == "__main__":
    unittest.main()
