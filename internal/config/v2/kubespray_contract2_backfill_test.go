// Legacy config: deployment.kubespray block without module sources must get
// the contract v2 pin backfilled at load, so a re-render resolves a module
// that accepts inventory_output_dir.
func TestNormalizeBackfillsKubesprayModuleSource(t *testing.T) {
	legacy := `---
schema_version: "2.0"
opencenter:
  meta:
    name: argus
deployment:
  auto_deploy: true
  method: kubespray
  kubespray:
    version: 2.31.0
`
	cfg, err := DecodePublicConfig([]byte(legacy))
	if err != nil {
		t.Fatal(err)
	}
	cl := NewConfigLoader(nil)
	if err := cl.normalize(cfg); err != nil {
		t.Fatal(err)
	}
	if cfg.Deployment.Kubespray == nil {
		t.Fatal("nil kubespray")
	}
	if !strings.Contains(cfg.Deployment.Kubespray.KubesprayCluster.Source, "2026.03-rc4") {
		t.Fatalf("kubespray_cluster source not backfilled: %q", cfg.Deployment.Kubespray.KubesprayCluster.Source)
	}
	if !strings.Contains(cfg.Deployment.Kubespray.Modules["kubespray"].Source, "2026.03-rc4") {
		t.Fatalf("modules.kubespray source not backfilled: %#v", cfg.Deployment.Kubespray.Modules)
	}
}

// Explicit user pin must survive untouched.
func TestNormalizeKeepsExplicitKubesprayModuleSource(t *testing.T) {
	cfg, err := DecodePublicConfig([]byte(`---
schema_version: "2.0"
opencenter:
  meta:
    name: argus
deployment:
  auto_deploy: true
  method: kubespray
  kubespray:
    version: 2.31.0
    kubespray_cluster:
      source: github.com/example/fork.git//iac/provider/kubespray?ref=my-branch
      enabled: true
`))
	if err != nil {
		t.Fatal(err)
	}
	cl := NewConfigLoader(nil)
	if err := cl.normalize(cfg); err != nil {
		t.Fatal(err)
	}
	if got := cfg.Deployment.Kubespray.KubesprayCluster.Source; got != "github.com/example/fork.git//iac/provider/kubespray?ref=my-branch" {
		t.Fatalf("explicit source overwritten: %q", got)
	}
}

// A config generated by an older CLI stamped the stale base release into the
// kubespray module slots. The loader must upgrade the stale gitops-base pin to
// the contract v2 ref (the CLI deploy path always renders in lifecycle mode,
// so a pre-contract-2 ref breaks kubespray-prepare), while a pin outside the
// gitops-base kubespray module path stays untouched.
func TestNormalizeUpgradesStaleKubesprayModulePin(t *testing.T) {
	cfg, err := DecodePublicConfig([]byte(`---
schema_version: "2.0"
opencenter:
  meta:
    name: argus
deployment:
  auto_deploy: true
  method: kubespray
  kubespray:
    version: 2.31.0
    kubespray_cluster:
      source: github.com/opencenter-cloud/openCenter-gitops-base.git//iac/provider/kubespray?ref=2026.03-rc3
      enabled: true
    modules:
      kubespray:
        source: github.com/example/fork.git//iac/provider/kubespray?ref=my-branch
        enabled: true
`))
	if err != nil {
		t.Fatal(err)
	}
	cl := NewConfigLoader(nil)
	if err := cl.normalize(cfg); err != nil {
		t.Fatal(err)
	}
	if got := cfg.Deployment.Kubespray.KubesprayCluster.Source; got != DefaultKubesprayModuleSourceURL {
		t.Fatalf("stale gitops-base pin not upgraded: %q", got)
	}
	if got := cfg.Deployment.Kubespray.Modules["kubespray"].Source; got != "github.com/example/fork.git//iac/provider/kubespray?ref=my-branch" {
		t.Fatalf("fork pin overwritten: %q", got)
	}
	if RequiresKubesprayModuleContract2Upgrade(cfg) {
		t.Fatal("upgraded config still flagged for upgrade")
	}
}

// The generation gate must block a config whose module slots still pin a
// pre-contract-2 gitops-base ref, naming the contract and the repair command.
func TestValidateGenerationBlocksStaleKubesprayModulePin(t *testing.T) {
	cfg, err := NewV2Default("stale-gate", "openstack")
	if err != nil {
		t.Fatal(err)
	}
	module := cfg.Deployment.Kubespray.Modules["kubespray"]
	module.Source = "github.com/opencenter-cloud/openCenter-gitops-base.git//iac/provider/kubespray?ref=2026.03-rc3"
	cfg.Deployment.Kubespray.Modules["kubespray"] = module

	report := ValidateGeneration(cfg)
	var found bool
	for _, issue := range report.Issues {
		if issue.Path == "deployment.kubespray" &&
			strings.Contains(issue.Message, "lifecycle contract 2") &&
			strings.Contains(issue.Message, "opencenter cluster set") {
			found = true
		}
	}
	if !found {
		t.Fatalf("stale kubespray pin not reported: %+v", report.Issues)
	}
	if report.Valid {
		t.Fatal("stale kubespray pin must invalidate the report")
	}
}

// Contract 3 is the opposite of the contract-2 gate: a pre-v3 module deploys and
// runs, it only leaves the network/subnet outputs unavailable. So it must warn
// without invalidating the report, and the repair it names has to actually clear
// it -- suggesting the v2 default instead would leave an operator running a
// command that never silences the warning.
func TestValidateGenerationWarnsOnContract3Gap(t *testing.T) {
	cfg, err := NewV2Default("contract3-gap", "openstack")
	if err != nil {
		t.Fatal(err)
	}
	cfg.Deployment.Method = "kubespray"

	contract3Warning := func(report GenerationValidationReport) *ValidationIssue {
		for i, issue := range report.Issues {
			if issue.Path == "deployment.kubespray" &&
				issue.Severity == SeverityWarning &&
				strings.Contains(issue.Message, "lifecycle contract 3") {
				return &report.Issues[i]
			}
		}
		return nil
	}

	report := ValidateGeneration(cfg)
	warning := contract3Warning(report)
	if warning == nil {
		t.Fatalf("a v2-pinned module ref must report the contract 3 gap: %+v", report.Issues)
	}
	// The gap must arrive as a warning. Asserting on report.Valid instead would
	// be wrong twice over: a bare NewV2Default config carries unrelated
	// readiness errors (image_id, credentials, tokens), and a warning never
	// touches Valid, so Valid says nothing about this issue.
	if warning.Severity != SeverityWarning {
		t.Errorf("contract 3 gap severity = %q, want %q: it is advisory and must never block generation",
			warning.Severity, SeverityWarning)
	}

	// Follow the repair the message names.
	cfg.Deployment.Kubespray.KubesprayCluster.Source = DefaultKubesprayModuleSourceURLContract3
	for name, module := range cfg.Deployment.Kubespray.Modules {
		module.Source = DefaultKubesprayModuleSourceURLContract3
		cfg.Deployment.Kubespray.Modules[name] = module
	}
	if after := contract3Warning(ValidateGeneration(cfg)); after != nil {
		t.Errorf("the advertised repair does not clear the contract 3 warning: %s", after.Message)
	}
}

// Only openstack gains the outputs: the baremetal and vmware templates declare no
// openstack-nova module, so flagging them would push a repair that can never
// apply.
func TestContract3GapIgnoresNonOpenStackProviders(t *testing.T) {
	for _, provider := range []string{"baremetal", "vmware", "kind", "magnum"} {
		t.Run(provider, func(t *testing.T) {
			cfg, err := NewV2Default("gap-"+provider, provider)
			if err != nil {
				t.Fatal(err)
			}
			cfg.Deployment.Method = "kubespray"
			if ReportsKubesprayModuleContract3Gap(cfg) {
				t.Errorf("provider %q must never report the contract 3 gap", provider)
			}
		})
	}
}
